-- ==============================================================================
-- UEHIS PRODUCTION DATABASE MIGRATION - GEOMETRY CORRECTION
-- Separating Candidate Opportunity Masks from Actual Planting Units
-- ==============================================================================

-- 1. Remove the fundamentally flawed table and its centroid-derived rows
DROP TABLE IF EXISTS planting_candidates CASCADE;

-- 2. Create planting_candidate_areas (MultiPolygons representing opportunity masks)
CREATE TABLE planting_candidate_areas (
    area_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    geom geometry(MultiPolygon, 32643) NOT NULL,
    
    -- Attributes explicitly representing boundaries, not confirmed sites
    candidate_category TEXT NOT NULL DEFAULT 'unknown',
    ownership_status TEXT NOT NULL DEFAULT 'unknown',
    permission_status TEXT NOT NULL DEFAULT 'unknown',
    utility_status TEXT NOT NULL DEFAULT 'unknown',
    verification_status TEXT NOT NULL DEFAULT 'required',
    
    -- Provenance Links
    methodology_id UUID NOT NULL REFERENCES methodology_versions(id),
    production_run_id UUID NOT NULL REFERENCES production_runs(id)
);

-- 3. Create planting_units (Points generated by the optimizer)
CREATE TABLE planting_units (
    unit_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    geom geometry(Point, 32643) NOT NULL,
    
    -- Explicitly communicating that this is a hypothetical spatial point
    verification_status TEXT NOT NULL DEFAULT 'required',
    
    -- Provenance Links
    methodology_id UUID NOT NULL REFERENCES methodology_versions(id),
    production_run_id UUID NOT NULL REFERENCES production_runs(id)
);

-- 4. Create planting_scenario_units (Normalization mapping)
-- Preserves analytical subsets (100k, 250k) without duplicating Point geometries.
CREATE TABLE planting_scenario_units (
    scenario_id UUID NOT NULL REFERENCES planting_scenarios(scenario_id) ON DELETE CASCADE,
    unit_id UUID NOT NULL REFERENCES planting_units(unit_id) ON DELETE CASCADE,
    PRIMARY KEY (scenario_id, unit_id)
);

-- 5. Create GiST and B-Tree Indexes
CREATE INDEX idx_planting_candidate_areas_geom ON planting_candidate_areas USING GIST (geom);
CREATE INDEX idx_planting_candidate_areas_prod_run ON planting_candidate_areas USING btree (production_run_id);
CREATE INDEX idx_planting_candidate_areas_methodology ON planting_candidate_areas USING btree (methodology_id);

CREATE INDEX idx_planting_units_geom ON planting_units USING GIST (geom);
CREATE INDEX idx_planting_units_prod_run ON planting_units USING btree (production_run_id);
CREATE INDEX idx_planting_units_methodology ON planting_units USING btree (methodology_id);

CREATE INDEX idx_planting_scenario_units_scenario ON planting_scenario_units USING btree (scenario_id);
CREATE INDEX idx_planting_scenario_units_unit ON planting_scenario_units USING btree (unit_id);

-- 6. Apply RLS Constraints
ALTER TABLE planting_candidate_areas ENABLE ROW LEVEL SECURITY;
ALTER TABLE planting_units ENABLE ROW LEVEL SECURITY;
ALTER TABLE planting_scenario_units ENABLE ROW LEVEL SECURITY;

